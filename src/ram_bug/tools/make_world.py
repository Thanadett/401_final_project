#!/usr/bin/env python3
"""
Make a random 3 x 3 m Gazebo (Harmonic) world for testing, like the competition:
random boxes, our robot start, a goal, and the chaser starting in view 1-3 m away
(--scenario trap: chaser starts >= 1.5 m from the goal).

  python3 tools/make_world.py --seed 7            -> worlds/arena_7.sdf + worlds/arena_7.json
  then rebuild:  colcon build --packages-select ram_bug
  and run:       ros2 launch ram_bug sim.launch.py world:=arena_7

The json holds start / goal / chaser positions (arena frame, metres) and the
obstacle cells; sim.launch.py reads it.
"""
import argparse
import json
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
from ram_bug import eg_core as eg   # noqa: E402

C = eg.CELL


def box(name, cx, cy, sx, sy, h, rgba):
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{cx:.3f} {cy:.3f} {h / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {h:.3f}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material></visual>
      </link>
    </model>"""


def runs(cells):
    """merge obstacle cells into horizontal strips (fewer Gazebo models)."""
    out = []
    for y in range(eg.H):
        x = 0
        while x < eg.W:
            if eg.idx(x, y) in cells:
                x0 = x
                while x < eg.W and eg.idx(x, y) in cells:
                    x += 1
                out.append((x0, y, x - x0))
            else:
                x += 1
    return out


def chaser_model(x, y):
    return f"""
    <model name="chaser">
      <pose>{x:.3f} {y:.3f} 0.101 0 0 0</pose>
      <link name="body">
        <inertial><mass>1.0</mass>
          <inertia><ixx>0.005</ixx><iyy>0.005</iyy><izz>0.003</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="c"><geometry><cylinder><radius>0.07</radius><length>0.2</length></cylinder></geometry>
          <surface><friction><ode><mu>0.0</mu><mu2>0.0</mu2></ode></friction></surface></collision>
        <visual name="v"><geometry><cylinder><radius>0.07</radius><length>0.2</length></cylinder></geometry>
          <material><ambient>0.9 0.2 0.3 1</ambient><diffuse>0.9 0.2 0.3 1</diffuse></material></visual>
      </link>
      <plugin filename="gz-sim-velocity-control-system" name="gz::sim::systems::VelocityControl"/>
      <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">
        <odom_topic>/chaser/odom</odom_topic>
        <odom_frame>arena</odom_frame>
        <robot_base_frame>chaser</robot_base_frame>
        <dimensions>2</dimensions>
        <odom_publish_frequency>20</odom_publish_frequency>
      </plugin>
    </model>"""


def make(seed, out_dir, scenario="friend"):
    rng = random.Random(seed)
    while True:
        obst, start, goal, cst = eg.random_round(rng, scenario)
        # keep robots and goal >= 0.2 m from the walls (the Burger is 0.14-0.18 m wide)
        if all(2 <= v <= eg.W - 3 for c in (start, goal, cst) for v in eg.xy(c)):
            break
    sx, sy = [v * C for v in eg.center(start)]
    gx, gy = [v * C for v in eg.center(goal)]
    cx, cy = [v * C for v in eg.center(cst)]
    models = []
    for k, (x0, y, n) in enumerate(runs(obst)):
        models.append(box(f"obstacle_{k}", (x0 + n / 2) * C, (y + 0.5) * C, n * C, C, 0.25, "0.6 0.55 0.7 1"))
    t, L = 0.05, 3.0
    for name, x, y, a, b in (("wall_s", L / 2, -t / 2, L + 2 * t, t), ("wall_n", L / 2, L + t / 2, L + 2 * t, t),
                             ("wall_w", -t / 2, L / 2, t, L), ("wall_e", L + t / 2, L / 2, t, L)):
        models.append(box(name, x, y, a, b, 0.25, "0.3 0.3 0.35 1"))
    # goal marker (visual only)
    models.append(f"""
    <model name="goal_marker"><static>true</static><pose>{gx:.3f} {gy:.3f} 0.002 0 0 0</pose>
      <link name="l"><visual name="v"><geometry><cylinder><radius>0.15</radius><length>0.004</length></cylinder></geometry>
        <material><ambient>1 0.85 0.3 1</ambient><diffuse>1 0.85 0.3 1</diffuse></material></visual></link></model>""")
    models.append(chaser_model(cx, cy))
    sdf = f"""<?xml version="1.0" ?>
<!-- generated by tools/make_world.py (seed {seed}): 3 x 3 m arena, origin = arena corner -->
<sdf version="1.8">
  <world name="arena">
    <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <light type="directional" name="sun"><cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><direction>-0.3 0.2 -0.9</direction></light>
    <model name="ground_plane"><static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.8 0.8 0.8 1</ambient><diffuse>0.8 0.8 0.8 1</diffuse></material></visual>
      </link>
    </model>{''.join(models)}
  </world>
</sdf>
"""
    os.makedirs(out_dir, exist_ok=True)
    name = f"arena_{seed}"
    with open(os.path.join(out_dir, name + ".sdf"), "w", encoding="utf-8") as f:
        f.write(sdf)
    info = dict(seed=seed, start_x=sx, start_y=sy, start_yaw=0.0, goal_x=gx, goal_y=gy,
                chaser_x=cx, chaser_y=cy, obstacle_cells=sorted(obst))
    with open(os.path.join(out_dir, name + ".json"), "w", encoding="utf-8") as f:
        json.dump(info, f, indent=1)
    print(f"{name}: start ({sx:.2f}, {sy:.2f})  goal ({gx:.2f}, {gy:.2f})  chaser ({cx:.2f}, {cy:.2f})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, nargs="+", default=[1])
    ap.add_argument("--out", default=os.path.join(HERE, "..", "worlds"))
    ap.add_argument("--scenario", default="friend", choices=["friend", "trap"],
                    help="friend: chaser starts in view 1-3 m away (real match); trap: far from the goal")
    a = ap.parse_args()
    for s in a.seed:
        make(s, a.out, a.scenario)
